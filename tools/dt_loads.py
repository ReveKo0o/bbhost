#!/usr/bin/env python3
"""Generate src/engine/frame_rate_dt_loads.inc - the loads engine/frame_rate.cpp redirects to slots that
follow the frame's time (kDtLoads) - from tools/dt_loads.txt and the 1.09 eboot:

    tools/dt_loads.py eboot-109-decrypted.bin

Each line of dt_loads.txt names an instruction (Binary Ninja address: the ELF's VA + 0x400000), its
length, where its 4-byte rip displacement starts, the constant it reads, how that value follows the
frame's time (Step, Amount, Decay, Keep, Rate) and how many float lanes it reads (1, 2 or 4). The tool
checks that the displacement resolves to the constant and copies the instruction's bytes from the eboot
into the table, so frame_rate.cpp can refuse an eboot whose bytes differ. Finding the readers of a
constant is not this tool's job: every rip-relative instruction of every function is the list to look
in, and a constant read by a lea (its address taken) or a vector read one lane at a time needs a person.
"""
import os
import struct
import sys

KINDS = ('Step', 'Amount', 'Decay', 'Keep', 'Rate')


def segments(eb):
    phoff, phnum = struct.unpack_from('<Q', eb, 0x20)[0], struct.unpack_from('<H', eb, 0x38)[0]
    out = []
    for i in range(phnum):
        t, fl, off, va, pa, fs, ms, al = struct.unpack_from('<IIQQQQQQ', eb, phoff + i * 56)
        if t == 1:
            out.append((va + 0x400000, off, fs))
    return out


def read(eb, segs, a, n):
    for va, off, fs in segs:
        if va <= a and a + n <= va + fs:
            return eb[off + a - va:off + a - va + n]
    raise SystemExit('0x%x is not in the eboot\'s file image' % a)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    eb = open(sys.argv[1], 'rb').read()
    segs = segments(eb)
    here = os.path.dirname(os.path.abspath(__file__))
    rows = []
    for line in open(os.path.join(here, 'dt_loads.txt'), encoding='utf-8'):
        body, _, comment = line.partition('#')
        f = body.split()
        if not f:
            continue
        insn, length, disp, const, kind, lanes = int(f[0], 16), int(f[1]), int(f[2]), int(f[3], 16), f[4], int(f[5])
        if kind not in KINDS or lanes not in (1, 2, 4) or not 0 < disp <= length - 4:
            raise SystemExit('bad line: ' + line.strip())
        b = read(eb, segs, insn, length)
        if insn + length + struct.unpack_from('<i', b, disp)[0] != const:
            raise SystemExit('0x%x does not read 0x%x' % (insn, const))
        vals = struct.unpack('<%df' % lanes, read(eb, segs, const, 4 * lanes))
        rows.append((insn, length, disp, const, kind, lanes, b.hex(), vals, comment.strip()))
    out = os.path.join(here, '..', 'src', 'engine', 'frame_rate_dt_loads.inc')
    with open(out, 'w') as o:
        o.write('// Generated by tools/dt_loads.py from tools/dt_loads.txt and the 1.09 eboot: each load to redirect -\n')
        o.write('// the instruction (Binary Ninja), its length, its rip displacement\'s offset, the constant it reads,\n')
        o.write('// how that value follows the frame\'s time, the lanes, and the instruction\'s bytes.\n')
        for insn, length, disp, const, kind, lanes, hx, vals, comment in rows:
            o.write('    {0x%08x, %d, %d, 0x%08x, Kind::%s, %d, "%s"},  // [%s] %s\n' %
                    (insn, length, disp, const, kind, lanes, hx, ', '.join('%g' % v for v in vals), comment))
        o.write('// %d loads of %d constants\n' % (len(rows), len(set(r[3] for r in rows))))
    print('wrote %s: %d loads' % (os.path.normpath(out), len(rows)))


main()
